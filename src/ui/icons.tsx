// Icon names are plain strings in commands and history (so they serialize);
// this maps them to lucide components.
import {
  Box,
  Circle,
  Combine,
  Copy,
  Cylinder,
  Download,
  Eye,
  EyeOff,
  File,
  FolderOpen,
  Grid2x2,
  Move3d,
  MousePointer2,
  PenLine,
  Pencil,
  Redo2,
  Rotate3d,
  Ruler,
  Save,
  Scaling,
  Shapes,
  Sparkles,
  SquareDashed,
  SquaresIntersect,
  SquaresSubtract,
  SquaresUnite,
  Spline,
  Trash2,
  Triangle,
  Type,
  Undo2,
  ArrowDownToLine,
  Crosshair,
  Layers,
  type LucideIcon,
} from "lucide-react";

export const ICONS = {
  box: Box,
  cylinder: Cylinder,
  sphere: Circle,
  cone: Triangle,
  torus: Spline,
  shapes: Shapes,
  select: MousePointer2,
  sketch: PenLine,
  extrude: Layers,
  text: Type,
  pattern: Grid2x2,
  move: Move3d,
  rotate: Rotate3d,
  resize: Scaling,
  fillet: SquareDashed,
  union: SquaresUnite,
  subtract: SquaresSubtract,
  intersect: SquaresIntersect,
  boolean: Combine,
  duplicate: Copy,
  delete: Trash2,
  visible: Eye,
  hidden: EyeOff,
  rename: Pencil,
  dropToBed: ArrowDownToLine,
  center: Crosshair,
  file: File,
  open: FolderOpen,
  save: Save,
  export: Download,
  undo: Undo2,
  redo: Redo2,
  measure: Ruler,
  ai: Sparkles,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 16, ...rest }: { name: IconName; size?: number; className?: string; strokeWidth?: number }) {
  const C = ICONS[name];
  return <C size={size} strokeWidth={rest.strokeWidth ?? 1.75} className={rest.className} />;
}
